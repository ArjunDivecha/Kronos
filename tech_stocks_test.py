    "DDOG", "ZS", "CRWD", "NET", "OKTA", "TEAM", "HUBS", "WDAY",
    "VEEV", "PANW", "FTNT", "ZM",
    # Internet / E-commerce
    "NFLX", "UBER", "LYFT", "ABNB", "DASH", "PINS", "SNAP", "RBLX",
    # Hardware / Infrastructure
    "ANET", "HPE", "DELL", "NTAP", "PSTG", "SMCI", "GLW",
    # Payments / Fintech
    "PYPL", "SQ", "COIN",
