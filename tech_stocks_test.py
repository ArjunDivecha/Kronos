    "AAPL", "MSFT", "NVDA", "GOOGL", "META", "AMZN", "TSLA", "AVGO",
    # Semiconductors
    "AMD", "QCOM", "TXN", "INTC", "AMAT", "LRCX", "KLAC", "MRVL",
